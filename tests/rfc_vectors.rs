/// Cross-check: an independent reproduction of the first RFC 4226 Appendix D vector with a
/// hand-written HMAC-SHA-1.
///
/// The vector tests above verify the **combined** result of `hmac_truncate` + `hotp`, so a dynamic
/// truncation and an HMAC call that are both wrong could still agree by chance. This test computes
/// the same value through a second path: `hmac`/`sha1` directly, with the dynamic truncation
/// (RFC 4226 §5.3) and the modulus written out by hand. It also confirms that the `SimpleHmac` API
/// gives the same result, since that route bypasses this crate's dispatch and truncation code.
///
/// The check also pins the SHA-1 digest length at 20 bytes, which is what makes `digest[19]` the
/// last byte of the digest.
#[test]
fn cross_check_hotp_counter_zero_against_manual_hmac() {
    use hmac::digest::{Digest, KeyInit, Mac};

    let mut mac = <hmac::SimpleHmac<sha1::Sha1> as KeyInit>::new_from_slice(RFC_SECRET_ASCII)
        .expect("HMAC 接受任意长度密钥");
    Mac::update(&mut mac, &0_u64.to_be_bytes());
    let digest = Mac::finalize(mac).into_bytes();

    let offset = usize::from(digest[19] & 0x0f);
    let bin = (u32::from(digest[offset]) & 0x7f) << 24
        | u32::from(digest[offset + 1]) << 16
        | u32::from(digest[offset + 2]) << 8
        | u32::from(digest[offset + 3]);
    let manual = format!("{:06}", bin % 1_000_000);

    assert_eq!(manual, "755224", "手写实现应与 RFC 4226 附录 D 一致");

    let secret = OtpSecret::from_bytes(RFC_SECRET_ASCII.to_vec()).expect("种子非空");
    assert_eq!(
        otp::hotp_code(&secret, 0, Algorithm::Sha1, Digits::Six),
        manual
    );

    let sha1_len = <sha1::Sha1 as Digest>::output_size();
    assert_eq!(sha1_len, 20, "SHA-1 输出长度应为 20 字节");
}

/// The 8-digit and 6-digit expected values must agree with each other.
///
/// RFC 6238 Appendix B uses 8 digits while RFC 4226 Appendix D uses 6, and both are the same
/// truncated value reduced modulo a different power of ten. For a single counter and a single
/// algorithm the two codes therefore differ only in the digit count: the 6-digit code is the last 6
/// digits of the 8-digit one, and Appendix D gives `287082` for counter 1. This catches a digit
/// count that never actually takes effect.
#[test]
fn digit_count_actually_changes_the_modulus() {
    let secret = OtpSecret::from_bytes(RFC_SECRET_ASCII.to_vec()).expect("种子非空");
    let counter = 1_u64;

    let six = otp::hotp_code(&secret, counter, Algorithm::Sha1, Digits::Six);
    let eight = otp::hotp_code(&secret, counter, Algorithm::Sha1, Digits::Eight);

    assert_eq!(six.len(), 6);
    assert_eq!(eight.len(), 8);
    assert_eq!(
        &eight[eight.len() - 6..],
        six,
        "6 位码应是 8 位码对 10^6 取模的结果"
    );

    assert_eq!(six, "287082");
}

/// Seven digits has no vector in either RFC, but must be mathematically consistent with 6 and 8.
///
/// The 7-digit code is the same truncated value reduced modulo 10^7, so it must be the last 7 digits
/// of the 8-digit code for the same counter.
#[test]
fn seven_digits_is_self_consistent() {
    let secret = OtpSecret::from_bytes(RFC_SECRET_ASCII.to_vec()).expect("种子非空");
    let seven = otp::hotp_code(&secret, 1, Algorithm::Sha1, Digits::Seven);
    let eight = otp::hotp_code(&secret, 1, Algorithm::Sha1, Digits::Eight);

    assert_eq!(seven.len(), 7);
    assert_eq!(
        &eight[eight.len() - 7..],
        seven,
        "7 位码应是 8 位码对 10^7 取模的结果"
    );
}

/// Leading zeros must be preserved in the output.
///
/// Every code is a 6-digit decimal string, so an implementation that rendered the truncated value as
/// an integer would drop a leading zero and return a code of the wrong length. The test walks 200
/// consecutive 30-second steps of the Base32 seed `"JBSWY3DPEHPK3PXP"`; each code must be 6 ASCII
/// digits and, wherever a code starts with `0`, its numeric value must be below 100000 and
/// `format_code` must pad it back to 6 digits. It fails if no leading-zero case shows up in those
/// steps, because the property would then go unverified.
#[test]
fn leading_zeros_are_preserved_in_output() {
    let secret = OtpSecret::from_base32("JBSWY3DPEHPK3PXP").expect("合法 Base32 种子");

    let mut found_leading_zero = false;
    for step in 0_u64..200 {
        let code = otp::totp_code(&secret, step * 30, 30, Algorithm::Sha1, Digits::Six)
            .expect("period 非零");
        assert_eq!(code.len(), 6, "任何情况下都必须是 6 位：{code}");
        assert!(
            code.chars().all(|c| c.is_ascii_digit()),
            "必须全是 ASCII 数字：{code}"
        );
        if code.starts_with('0') {
            found_leading_zero = true;
            let numeric: u32 = code.parse().expect("应可解析为数字");
            assert!(numeric < 100_000, "带前导零的码应小于 100000：{code}");
            assert_eq!(otp::format_code(numeric, Digits::Six), code);
        }
    }
    assert!(
        found_leading_zero,
        "200 个时间步内未出现前导零案例，本测试未能覆盖目标场景"
    );
}
