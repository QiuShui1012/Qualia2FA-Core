//! RFC official test vectors — the acceptance criterion for the OTP code paths.
//!
//! These vectors come from the specification text rather than being generated by this repository.
//! Any failure means the implementation does not conform to the standard, and therefore that real
//! users would be shown wrong codes.
//!
//! | Specification | Source | Coverage |
//! |---|---|---|
//! | RFC 4226 | Appendix D | the ten HMAC-SHA-1 HOTP vectors |
//! | RFC 6238 | Appendix B | the SHA-1 / SHA-256 / SHA-512 TOTP vector sets |
//! | RFC 6238 | Appendix A | how the seeds are built (used to reproduce Appendix B) |
//! | RFC 4648 | §10 | Base32 encoding and decoding vectors (see the unit tests in `src/base32.rs`) |
//!
//! These vectors are an **external commitment**, not an implementation detail: they live in their
//! own integration test file so that the coverage can be read at a glance, and changing one requires
//! changing the specification reference with it.

use qualia2fa_core::otp::{self, Algorithm, Digits, OtpSecret};

/// The ASCII seed `"12345678901234567890"` used by RFC 4226 and RFC 6238.
///
/// It is a fixed value the specifications chose so that the vectors can be reproduced, **not** a
/// random secret, and it must never be used in production.
const RFC_SECRET_ASCII: &[u8] = b"12345678901234567890";

/// RFC 6238 Appendix A: the SHA-256 and SHA-512 seeds are each a repetition of the SHA-1 seed.
///
/// The specification states that SHA-1 uses 20 bytes, SHA-256 uses 32 bytes and SHA-512 uses 64
/// bytes, the latter two built by repeating the first. The seeds here are constructed that way.
fn seed_of_len(len: usize) -> Vec<u8> {
    let mut seed = Vec::with_capacity(len);
    while seed.len() < len {
        seed.extend_from_slice(RFC_SECRET_ASCII);
    }
    seed.truncate(len);
    seed
}

/// RFC 4226 Appendix D — all ten HOTP vectors.
///
/// The table in Appendix D gives the 6-digit decimal HOTP value for each `Count` from 0 to 9.
#[test]
fn rfc4226_appendix_d_all_ten_vectors() {
    /// Line-by-line transcription of the Appendix D table (counter, expected 6-digit code).
    const VECTORS: [(u64, &str); 10] = [
        (0, "755224"),
        (1, "287082"),
        (2, "359152"),
        (3, "969429"),
        (4, "338314"),
        (5, "254676"),
        (6, "287922"),
        (7, "162583"),
        (8, "399871"),
        (9, "520489"),
    ];

    let secret = OtpSecret::from_bytes(RFC_SECRET_ASCII.to_vec()).expect("种子非空");

    for (counter, expected) in VECTORS {
        let got = otp::hotp_code(&secret, counter, Algorithm::Sha1, Digits::Six);
        assert_eq!(
            got, expected,
            "RFC 4226 附录 D 计数器 {counter} 不符：期望 {expected}，实际 {got}"
        );
    }
}

/// RFC 6238 Appendix B — the three TOTP vector sets.
///
/// Appendix B gives six time points (T = 59, 1111111109, 1111111111, 1234567890, 2000000000,
/// 20000000000), each with an 8-digit expected value for every one of the three algorithms.
///
/// Note that the **digit count is 8**, the form the Appendix B table uses, unlike the 6 digits of
/// Appendix D.
#[test]
fn rfc6238_appendix_b_sha1_vectors() {
    const VECTORS: [(u64, &str); 6] = [
        (59, "94287082"),
        (1_111_111_109, "07081804"),
        (1_111_111_111, "14050471"),
        (1_234_567_890, "89005924"),
        (2_000_000_000, "69279037"),
        (20_000_000_000, "65353130"),
    ];

    let secret = OtpSecret::from_bytes(seed_of_len(20)).expect("种子非空");

    for (time, expected) in VECTORS {
        let got =
            otp::totp_code(&secret, time, 30, Algorithm::Sha1, Digits::Eight).expect("period 非零");
        assert_eq!(
            got, expected,
            "RFC 6238 附录 B (SHA-1) T={time} 不符：期望 {expected}，实际 {got}"
        );
    }
}

